const arabicIndicMap = {
  '0': '٠', '1': '١', '2': '٢', '3': '٣', '4': '٤',
  '5': '٥', '6': '٦', '7': '٧', '8': '٨', '9': '٩'
};

export const convertToArabicIndicNumerals = (text: string | number, lang: Language): string => {
  if (lang !== Language.KU_BADINI && lang !== Language.AR) {
    return String(text);
  }
  const str = String(text);
  return str.split('').map(char => arabicIndicMap[char as keyof typeof arabicIndicMap] || char).join('');
};

